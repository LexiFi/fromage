(* The driver of the checks of [Roundtrip]: it checks the OCaml files of the
   repository, or sentences generated by ocamlgrammarfuzzer from the grammar
   of the compiler (parsing/parser.mly, copied in test/parser.mly), compiled
   by Menhir, with mutants of each one. The configurations of the fuzzer,
   and the dune rules which check its sentences, are in
   [Fuzz_configurations].

   Usage ([--help] for all the options):
   driver.exe --repository [OPTION]...
   driver.exe --file FILE... [OPTION]...
   driver.exe --grammar GRAMMAR [OPTION]... [-- ENTRYPOINT FUZZER-ARGUMENT...]
   driver.exe --sentences FILE [OPTION]...

   With [--repository], the files are those which git lists, untracked ones
   included; with [--file], the given ones. They have no mutants by default.

   The sentences are generated by ocamlgrammarfuzzer ([--fuzzer], from the
   grammar compiled by [--menhir]), or read from FILE, which
   [fuzz_generate.exe sentences] writes, for the dune rules. Without an entry
   point, the sentences of the configurations are checked; with [--quick],
   only those of [runtest]; with [--entrypoint ENTRYPOINT], only those of
   this entry point. With an entry point ([implementation] or [interface]),
   the sentences generated with the given arguments are, for larger runs:
   driver.exe --grammar GRAMMAR -- interface --seed 4 --count 100000

   Options, which add mutants to each source:
   - [--every-token]: for each token of [Random_token.all], a mutant with this
     token inserted at a random position, and one with it replacing a random
     token;
   - [--mutants N]: [N] mutants with a random token inserted, and [N] with a
     random token replacing one.
   - [--doc-comments]: instead of the other mutants, mutants with a doc
     comment before every token, after a space, a newline, a blank line, or
     one of them at random, which test the attachment of doc comments (the
     sentences of the exhaustive mode are mostly valid, unlike the random
     ones). The tests use one mutant, with random separators.
     Otherwise, each mutant has a single token inserted or replaced.

   With [--rejections], the sentences are not checked: the errors of the
   compiler on them are grouped by message and by the text at their location,
   with the shortest example of each, to see why generated sentences are
   invalid.

   Every failure is shown on the error output as soon as it is found, with a
   smaller source failing in the same way; the report at the end is on the
   standard output. *)

open Roundtrip
open Fuzz_configurations

(* Where the sentences come from: the fuzzer, on the grammar compiled by
   Menhir, or a file of its output ([--sentences FILE]). *)
type generator =
  | Fuzzer of { menhir : string; fuzzer : string; source : string }
  | Saved of string

(* The sources to check: sentences, or files. *)
type input = Sentences of generator | Files of string list

(* [next], with a blank before it when it would not be lexed as a separate
   token after [previous]. *)
let separated (previous : Ocst.Token.any_token) (next : Ocst.Token.any_token) =
  match next.kind with
  | `EOF -> next
  | _ ->
      let previous =
        Ocst.Token_stream.insert
          Ocst.Token_stream.empty { previous with leading = [] }
      in
      match Ocst.Token_stream.(tokens (insert_create_trivia previous next)) with
      | [ _; next ] -> next
      | _ -> assert false

(* The kind of a failure, without the source: "AST mismatch", "OCST parser
   failed"... *)
let failure_kind ~name message =
  let message =
    if String.starts_with ~prefix:name message then
      String.sub
        message (String.length name)
        (String.length message - String.length name)
    else message
  in
  let message =
    if String.starts_with ~prefix:": " message then
      String.sub message 2 (String.length message - 2)
    else message
  in
  match String.index_opt message ':' with
  | Some index -> String.sub message 0 index
  | None -> message

(* A smaller source failing in the same way as [source]: windows of tokens
   are removed, from the largest to single tokens, as long as [failing]
   holds, within a number of checks, for very long sources. *)
let minimize ?(budget = 5000) ~failing source =
  let budget = ref budget in
  let failing source = !budget > 0 && (decr budget; failing source) in
  let without tokens start length =
    let tokens = Array.of_list tokens in
    let after =
      Array.sub tokens (start + length) (Array.length tokens - start - length)
    in
    if start > 0 then after.(0) <- separated tokens.(start - 1) after.(0);
    Ocst.source_of_tokens
      (Array.to_list (Array.append (Array.sub tokens 0 start) after))
  in
  (* Windows of [length] tokens, from [start]. *)
  let rec windows source length start =
    let tokens = Ocst.lex source in
    if start + length > List.length tokens - 1 then source
    else
      let smaller = without tokens start length in
      if failing smaller then windows smaller length start
      else windows source length (start + 1)
  in
  let rec loop source length =
    let smaller = windows source length 0 in
    if length > 1 then loop smaller (length / 2)
    else if smaller <> source then
      loop smaller (List.length (Ocst.lex smaller) / 2)
    else smaller
  in
  loop source (max 1 (List.length (Ocst.lex source) / 2))

(* Invalid variants of a sentence, to check that OCST and the compiler reject
   the same sources, and that OCST then fails with a syntax error: the
   sentence without one of its tokens, a prefix of the sentence, the sentence
   with a random token inserted, and with a token replaced by a random one,
   and the [extra] mutants. The positions and the tokens are chosen from the
   sentence, deterministically. *)
let mutants ?(extra = No_extra) sentence =
  let tokens = Array.of_list (Ocst.lex sentence) in
  (* The tokens before [EOF]. *)
  let count = Array.length tokens - 1 in
  if count < 2 || extra = No_mutants then []
  else
    let random = Random.State.make [| Hashtbl.hash sentence |] in
    let source tokens = Ocst.source_of_tokens (Array.to_list tokens) in
    let deleted = Random.State.int random count in
    let prefix = 1 + Random.State.int random (count - 1) in
    let without =
      Array.append
        (Array.sub tokens 0 deleted)
        (Array.sub tokens (deleted + 1) (Array.length tokens - deleted - 1))
    in
    (* [removed] tokens at [index] replaced by [token], which takes the trivia
       before them. *)
    let splice ?(token = Random_token.random random) index ~removed =
      let token = { token with leading = tokens.(index).leading } in
      let token =
        if index = 0 then token else separated tokens.(index - 1) token
      in
      let after =
        Array.sub
          tokens (index + removed) (Array.length tokens - index - removed)
      in
      after.(0) <- separated token { (after.(0)) with leading = [] };
      source (Array.concat [ Array.sub tokens 0 index; [| token |]; after ])
    in
    let insert ?token () =
      splice ?token (Random.State.int random (count + 1)) ~removed:0
    in
    let replace ?token () =
      splice ?token (Random.State.int random count) ~removed:1
    in
    let inserted = insert () in
    let replaced = replace () in
    let extras =
      match extra with
      | No_extra | No_mutants -> []
      | Every_token ->
            Array.to_list Random_token.all
          |>
          List.concat_map (fun token -> [ insert ~token (); replace ~token () ])
      | Mutants count ->
          List.concat (List.init count (fun _ -> [ insert (); replace () ]))
      | Doc_comments { all } ->
          let separators = [| " "; "\n"; "\n\n" |] in
          (* A doc comment before every token, after [separator ()]. *)
          let documented separator =
            let previous = ref None in
              Array.to_list tokens
            |>
            List.mapi
              ( fun index (token : Ocst.Token.any_token) ->
                  let text = Printf.sprintf "(** d%d *)" index in
                  let doc : Ocst.Token.any_token =
                    { leading = [ Whitespace (separator ()) ];
                      kind = `DOCSTRING text
                    }
                  in
                  let doc =
                    match !previous with
                      Some previous -> separated previous doc
                    | None -> doc
                  in
                  let token = separated doc token in
                  previous := Some token; [ doc; token ]
              )
            |> List.concat
            |> Array.of_list
            |> source
          in
            ( if all then
                List.map
                  (fun separator -> documented (fun () -> separator))
                  (Array.to_list separators)
              else []
            )
          @ [ documented (fun () -> separators.(Random.State.int random 3)) ]
    in
    let usual =
      [ source without; source (Array.sub tokens 0 prefix); inserted; replaced ]
    in
    let mutants =
      match extra with
        Doc_comments _ | No_mutants -> []
      | _ -> usual
    in
    List.sort_uniq compare (List.filter (( <> ) sentence) (mutants @ extras))

(* The errors of the compiler on [sentences], by message and text at their
   location, most frequent first, with the shortest example of each. *)
let rejections ~entrypoint sentences =
  let interface = entrypoint = "interface" in
  let groups = Hashtbl.create 64 in
  List.iter
    ( fun sentence ->
        match compiler_error ~interface "fuzz" sentence with
        | None -> ()
        | Some ((loc : Location.t), message) ->
            let start = loc.loc_start.pos_cnum
            and stop = loc.loc_end.pos_cnum
            in
            let text =
              if
                start >= 0 && stop <= String.length sentence && start <= stop
              then String.sub sentence start (min 30 (stop - start))
              else ""
            in
            let message = List.hd (String.split_on_char '\n' message) in
            let key = message, text in
            (* The sentence, or the text before the error for long ones. *)
            let sentence =
              if
                  String.length sentence <= 300 || start < 0
                || start > String.length sentence
              then sentence
              else
                  "..."
                ^ String.sub sentence (max 0 (start - 60)) (min 60 start)
                ^ "<HERE>"
            in
            let count, example =
              Option.value (Hashtbl.find_opt groups key) ~default:(0, sentence)
            in
            let example =
              if String.length sentence < String.length example then sentence
              else example
            in
            Hashtbl.replace groups key (count + 1, example)
    )
    sentences
  ;
  let groups = List.of_seq (Hashtbl.to_seq groups) in
  let total =
    List.fold_left (fun total (_, (count, _)) -> total + count) 0 groups
  in
  Printf.printf
    "%s: %d sentences, %d rejected by the compiler\n"
    entrypoint (List.length sentences) total
  ;
    List.sort (fun (_, (left, _)) (_, (right, _)) -> compare right left) groups
  |>
  List.iteri
    ( fun index ((message, text), (count, example)) ->
        if index < 40 then
          Printf.printf "%6d  %s [%s]\n        %S\n" count message text example
    )

(* {1 Checking sources} *)

(* Of the checked sources and mutants, those which both parsers accept, which
   are compared in depth. *)
type counts =
  { mutable valid : int; mutable mutants : int; mutable accepted : int }

(* Checks the [sources] (each with its file name, used in locations), and
   their mutants ([extra]), or only their mutants ([mutants_only]).
   [name ~kind filename source] names a source in the failures ([kind] is
   [" mutant"] for a mutant), which are also shown as they happen, for long
   runs, with a smaller source failing in the same way, found within [budget]
   checks. *)
let check_sources ~budget ~name ~mutants_only ~extra sources =
  let counts = { valid = 0; mutants = 0; accepted = 0 } in
  let check_source ~kind filename source =
    let name = name ~kind filename source in
    let failure =
      failure
        ~name
        ( fun () ->
            let both = check ~name filename source in
            if kind <> "" then begin
              counts.mutants <- counts.mutants + 1;
              if both then counts.accepted <- counts.accepted + 1
            end
            else if both then counts.valid <- counts.valid + 1
        )
    in
    Option.iter
      ( fun { message; details } ->
          let kind = failure_kind ~name message in
          (* The backtrace of an exception of OCST. *)
          if
            kind = "OCST raised an exception" || kind = "OCST internal error"
          then
            Option.iter
              (fun details -> prerr_string (Lazy.force details)) details
          ;
          let failing source =
            match
              Roundtrip.failure
                ~name (fun () -> ignore (check ~name filename source))
            with
            | Some { message; _ } -> failure_kind ~name message = kind
            | None -> false
          in
          Printf.eprintf
            "%s\n  minimized: %S\n%!" message (minimize ~budget ~failing source)
      )
      failure
    ;
    failure
  in
  let failures =
    List.concat_map
      ( fun (filename, source) ->
            ( if mutants_only then []
              else Option.to_list (check_source ~kind:"" filename source)
            )
          @
            List.filter_map
              (check_source ~kind:" mutant" filename)
              ( Roundtrip.timed
                  "make the mutants" (fun () -> mutants ~extra source)
              )
      )
      sources
  in
  failures, counts

(* Checks the sentences of the [configurations], generated by [fuzz]. *)
let check_configurations ~timings ~mutants_only ~part fuzz configurations =
  let failures =
    List.concat_map
      ( fun ({ entrypoint; arguments; extra } as configuration) ->
          let start = Unix.gettimeofday () in
          let sentences =
            Roundtrip.timed
              "generate the sentences"
              (fun () -> sentences_of_output (fuzz configuration))
          in
          let sentences =
            match part with
            | None -> sentences
            | Some (part, count) ->
                List.filteri (fun index _ -> index mod count = part) sentences
          in
          let options =
            match extra with
            | No_extra -> ""
            | No_mutants -> " (no mutants)"
            | Every_token -> " --every-token"
            | Mutants count -> Printf.sprintf " --mutants %d" count
            | Doc_comments { all = true } -> " --doc-comments"
            | Doc_comments { all = false } -> " (doc comments)"
          in
          let options =
            match part with
            | Some (part, count) when count > 1 ->
                Printf.sprintf "%s --part %d/%d" options part count
            | _ -> options
          in
          let filename =
            if entrypoint = "interface" then "fuzz.mli" else "fuzz.ml"
          in
          let failures, { valid; mutants; accepted } =
            check_sources
              ~budget:5000
              ~name:
                ( fun ~kind _ sentence ->
                    Printf.sprintf "%s%s %S" entrypoint kind sentence
                )
              ~mutants_only ~extra
              (List.map (fun sentence -> filename, sentence) sentences)
          in
          if mutants_only then
            Printf.printf
              "%s %s%s (mutants only): %d mutants (%d accepted)\n%!" entrypoint
              (String.concat " " arguments) options mutants accepted
          else
            Printf.printf
              "%s %s%s: %d sentences (%d accepted by both parsers), %d mutants (%d accepted)\n%!" entrypoint (String.concat " " arguments) options
              (List.length sentences) valid mutants accepted
          ;
          if timings then
            Printf.eprintf
              "%8.2fs  %s %s%s\n%!" (Unix.gettimeofday () -. start)
              entrypoint (String.concat " " arguments) options
          ;
          failures
      )
      configurations
  in
  if timings then Roundtrip.print_timings ();
  report ~title:"OCST fuzzing round-trip" failures

(* The OCaml files of the repository, as git lists them, untracked ones
   included. *)
let repository_files root =
  let command =
    Printf.sprintf
      "git -C %s ls-files -co --exclude-standard -- '*.ml' '*.mli'"
      (Filename.quote root)
  in
  let channel = Unix.open_process_in command in
  let files = In_channel.input_lines channel in
  match Unix.close_process_in channel with
  | Unix.WEXITED 0 ->
      List.filter Sys.file_exists (List.map (Filename.concat root) files)
  | _ -> failwith "could not list OCaml source files"

(* Checks the [files], with the mutants of [extra]. Small files fail faster
   than long ones: the minimization is given fewer checks than for the
   sentences. *)
let check_files ~timings ~extra files =
  let failures, { valid; mutants; accepted } =
    check_sources
      ~budget:500 ~name:(fun ~kind filename _ -> filename ^ kind)
      ~mutants_only:false ~extra
      ( List.map
          (fun file -> file, In_channel.with_open_bin file In_channel.input_all)
          files
      )
  in
  Printf.printf
    "%d files (%d accepted by both parsers)%s\n" (List.length files) valid
    ( if extra = No_mutants then ""
      else Printf.sprintf ", %d mutants (%d accepted)" mutants accepted
    )
  ;
  if timings then Roundtrip.print_timings ();
  report ~title:"OCST codebase round-trip" failures

let main
    show_rejections timings mutants_only sentences menhir fuzzer
    source repository files quick entrypoints every_token
    mutant_count doc_comments index part deep explicit
  =
    Warnings.parse_options false "-a" |> ignore;
    let input =
      match sentences, source, repository, files with
      | Some file, None, false, [] -> Ok (Sentences (Saved file))
      | None, Some source, false, [] ->
          Ok (Sentences (Fuzzer { menhir; fuzzer; source }))
      | None, None, true, [] -> Ok (Files (repository_files (git_root ())))
      | None, None, false, _ :: _ -> Ok (Files files)
      | None, None, false, [] ->
          Error
            "one of --grammar, --sentences, --repository and --file is required"
      | _ ->
          Error "--grammar, --sentences, --repository and --file are exclusive"
    and extra =
      match every_token, mutant_count, doc_comments with
      | false, None, false -> Ok None
      | true, None, false -> Ok (Some Every_token)
      | false, Some count, false -> Ok (Some (Mutants count))
      | false, None, true -> Ok (Some (Doc_comments { all = true }))
      | _ -> Error "--every-token, --mutants and --doc-comments are exclusive"
    in
    match input, extra, explicit with
    | Error message, _, _ | _, Error message, _ -> Error message
    | _, _, entrypoint :: _
      when not (List.mem entrypoint [ "implementation"; "interface" ])
    -> Error ("unknown entry point " ^ entrypoint)
    | Ok input, Ok extra, _ ->
        match show_rejections, input, explicit with
        | true, Sentences (Fuzzer { menhir; fuzzer; source }),
          entrypoint :: arguments
        ->
            let cmly = grammar ~menhir source in
            rejections
              ~entrypoint
              ( sentences_of_output
                  ( fuzzer_output
                      ~fuzzer ~cmly ([ "--entrypoint"; entrypoint ] @ arguments)
                  )
              )
            ;
            Ok ()
        | true, _, _ ->
            Error
              "--rejections needs --grammar and ENTRYPOINT [FUZZER-ARGUMENT]..."
        | false, Files files, _ ->
            Ok
              ( check_files
                  ~timings ~extra:(Option.value extra ~default:No_mutants) files
              )
        | false, Sentences generator, _ ->
            let configurations =
              selected ~quick ~entrypoints ~extra ~index ~deep explicit
            in
            (* The output of the fuzzer for a configuration. *)
            let fuzz =
              match generator, configurations with
              | Fuzzer { menhir; fuzzer; source }, _ ->
                  let cmly = grammar ~menhir source in
                  Ok
                    ( fun { entrypoint; arguments; _ } ->
                        fuzzer_output
                          ~fuzzer ~cmly
                          ([ "--entrypoint"; entrypoint ] @ arguments)
                    )
              | Saved file, [ _ ] ->
                  Ok
                    ( fun _ ->
                        In_channel.with_open_bin file In_channel.input_all
                    )
              | Saved _, _ ->
                  Error
                    "--sentences FILE: the sentences of a single configuration"
            in
            Result.map
              ( fun fuzz ->
                  check_configurations
                    ~timings ~mutants_only ~part fuzz configurations
              )
              fuzz

let () =
  let open Cmdliner in
  let flag name doc = Arg.(value & flag & info [ name ] ~doc) in
  let show_rejections =
    flag
      "rejections"
      "Group the errors of the compiler on the sentences of ENTRYPOINT \
       [FUZZER-ARGUMENT]..., by message and text at their location, instead \
       of checking them."
  and timings =
    flag
      "timings"
      "Print the time of each configuration and of each phase of the checks \
       on the error output."
  and mutants_only =
    flag
      "mutants-only"
      "Check only the mutants of the sentences, which another rule checks."
  and sentences =
    Arg.(
      value
    & opt (some file) None
    &
      info
        [ "sentences" ] ~docv:"FILE"
        ~doc:
          "Read the sentences from FILE, written by $(b,fuzz_generate.exe \
           sentences)."
    )
  and menhir =
    Arg.(
      value & opt string "menhir"
      & info [ "menhir" ] ~docv:"PROGRAM" ~doc:"Menhir, for the grammar."
    )
  and fuzzer =
    Arg.(
      value & opt string "ocamlgrammarfuzzer"
      & info [ "fuzzer" ] ~docv:"PROGRAM" ~doc:"ocamlgrammarfuzzer."
    )
  and source =
    Arg.(
      value
    & opt (some file) None
    &
      info
        [ "grammar" ] ~docv:"GRAMMAR"
        ~doc:
          "The grammar of the compiler (parser.mly), to generate the sentences."
    )
  and repository =
    flag
      "repository"
      "Check the OCaml files of the repository, as git lists them, untracked \
       ones included, instead of sentences."
  and files =
    Arg.(
      value
    & opt_all file []
    &
      info
        [ "file" ] ~docv:"FILE"
        ~doc:"Check FILE (repeatable) instead of sentences, for debugging."
    )
  and quick =
    flag "quick" "The quicker configurations of $(b,runtest), not all of them."
  and entrypoints =
    Arg.(
      value
    &
      opt_all
        (enum [ "implementation", "implementation"; "interface", "interface" ])
        []
    &
      info
        [ "entrypoint" ] ~docv:"ENTRYPOINT"
        ~doc:"Only the configurations of ENTRYPOINT (repeatable)."
    )
  and every_token =
    flag
      "every-token"
      "For each token, a mutant of each sentence with this token inserted at \
       a random position, and one with it replacing a random token."
  and mutant_count =
    Arg.(
      value
    & opt (some int) None
    &
      info
        [ "mutants" ] ~docv:"N"
        ~doc:
          "N mutants of each sentence with a random token inserted, and N \
             with a random token replacing one."
    )
  and doc_comments =
    flag
      "doc-comments"
      "Instead of the other mutants, mutants with a doc comment before every \
       token, after a space, a newline, a blank line, or one of them at \
       random."
  and index =
    Arg.(
      value
    & opt (some int) None
    &
      info
        [ "configuration" ] ~docv:"I"
        ~doc:"Only the Ith configuration (from 0) of those selected."
    )
  and part =
    Arg.(
      value
    & opt (some (pair ~sep:'/' int int)) None
    & info [ "part" ] ~docv:"I/N" ~doc:"Only the sentences of index I modulo N."
    )
  and deep =
    Arg.(
      value
    &
      opt
        ( some
            ( enum
                (List.map (fun { name; _ } -> name, name) deep_configurations)
            )
        )
        None
    &
      info
        [ "deep" ] ~docv:"NAME"
        ~doc:"The configuration of the deep fuzzing NAME."
    )
  and explicit =
    Arg.(
      value
    & pos_all string []
    &
      info
        [] ~docv:"ENTRYPOINT [FUZZER-ARGUMENT]..."
        ~doc:
          "A configuration: the sentences generated by the fuzzer with \
             these arguments for ENTRYPOINT (implementation or interface), \
             after $(b,--)."
    )
  in
  let term =
    Term.(
      const main $ show_rejections $ timings $ mutants_only $ sentences $ menhir
      $ fuzzer $ source $ repository $ files $ quick $ entrypoints $ every_token
      $ mutant_count $ doc_comments $ index $ part $ deep $ explicit
    )
