    ( Cmd.eval_result
        ( Cmd.make
            ( Cmd.info
                "driver"
                ~doc:
                  "Check OCST against the compiler on the files of the \
                   repository, or on sentences of the grammar of OCaml."
            )
            term
        )
    )
