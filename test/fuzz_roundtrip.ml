(* Round-trip checks on sentences generated by ocamlgrammarfuzzer from the
   grammar of the compiler (parsing/parser.mly, copied in test/parser.mly),
   compiled by Menhir.

   Usage: fuzz_roundtrip.exe MENHIR FUZZER GRAMMAR [OPTIONS] [ENTRYPOINT FUZZER-ARGUMENTS...]
          fuzz_roundtrip.exe --sentences FILE [OPTIONS]

   The sentences are generated by FUZZER, or read from FILE, which
   [--generate] writes (see {!section-dune_rules}).

   Without an entry point, the sentences of the configurations below are
   checked; with [--quick [ENTRYPOINT]], only those of
   [quick_configurations] (for this entry point), for [runtest]. With an entry point ([implementation] or [interface]), the
   sentences generated with the given arguments are, for larger runs:
   fuzz_roundtrip.exe MENHIR FUZZER GRAMMAR interface --seed 4 --count 100000

   Options, which add mutants to each sentence:
   - [--every-token]: for each token of [Random_token.all], a mutant with this
     token inserted at a random position, and one with it replacing a random
     token;
   - [--mutants N]: [N] mutants with a random token inserted, and [N] with a
     random token replacing one.
   - [--doc-comments]: instead of the other mutants, mutants with a doc
     comment before every token, after a space, a newline, a blank line, or
     one of them at random, which test the attachment of doc comments (the
     sentences of the exhaustive mode are mostly valid, unlike the random
     ones). The tests use one mutant, with random separators.
     Otherwise, each mutant has a single token inserted or replaced.

   With [--rejections], the sentences are not checked: the errors of the
   compiler on them are grouped by message and by the text at their location,
   with the shortest example of each, to see why generated sentences are
   invalid.

   Every failure is shown on the error output as soon as it is found, with a
   smaller source failing in the same way; the report at the end is on the
   standard output. *)

open Roundtrip

(* Runs [program], with its error output shown only if it fails. *)
let run ?(stdout = Unix.stdout) program arguments =
  let errors = Filename.temp_file "ocst_fuzz" ".err" in
  let stderr = Unix.openfile errors [ Unix.O_WRONLY; Unix.O_TRUNC ] 0 in
  let pid =
    Unix.create_process
      program (Array.of_list (program :: arguments)) Unix.stdin stdout stderr
  in
  Unix.close stderr;
  let status = snd (Unix.waitpid [] pid) in
  let output = In_channel.with_open_bin errors In_channel.input_all in
  Sys.remove errors;
  if status <> Unix.WEXITED 0 then
    failwith
      ( Printf.sprintf
          "%s failed:\n%s" (String.concat " " (program :: arguments)) output
      )

(* The grammar of the compiler, [source], as a .cmly file. *)
let grammar ~menhir source =
  let directory = Filename.temp_dir "ocst_fuzz" "" in
  let mly = Filename.concat directory "parser.mly" in
  Out_channel.with_open_bin
    mly
    ( fun channel ->
        Out_channel.output_string
          channel (In_channel.with_open_bin source In_channel.input_all)
    )
  ;
  let null = Unix.openfile "/dev/null" [ Unix.O_WRONLY ] 0 in
  run
    ~stdout:null menhir
    [ "--lalr"; "--table"; "--cmly"; "--unused-tokens";
      "--base"; Filename.concat directory "parser"; mly
    ]
  ;
  Unix.close null;
  at_exit
    ( fun () ->
        Array.iter
          (fun file -> Sys.remove (Filename.concat directory file))
          (Sys.readdir directory)
        ;
        Sys.rmdir directory
    )
  ;
  Filename.concat directory "parser.cmly"

(* How the fuzzer prints identifiers, labels and strings: about 15
   characters long (instead of [x1]), so that some constructs are on one
   line and others on several lines when formatted. *)
let names =
  List.concat_map
    (fun terminal -> [ "--terminal"; terminal ])
    [ "LIDENT=x%d_identifier"; "UIDENT=X%d_Constructor";
      "LABEL=~label%d_name:"; "OPTLABEL=?optional_name:";
      {|STRING="s%d string"|}; "QUOTED_STRING_EXPR={%%ext|s%d string|}";
      "QUOTED_STRING_ITEM={%%%%ext|s%d string|}"
    ]

(* The output of the fuzzer: its sentences, each followed by \000. *)
let fuzzer_output ~fuzzer ~cmly arguments =
  let file = Filename.temp_file "ocst_fuzz" ".txt" in
  let output = Unix.openfile file [ Unix.O_WRONLY; Unix.O_TRUNC ] 0 in
  run ~stdout:output fuzzer ([ "--cmly"; cmly; "-0" ] @ names @ arguments);
  Unix.close output;
  let text = In_channel.with_open_bin file In_channel.input_all in
  Sys.remove file; text

(* Where the sentences come from: the fuzzer, on the grammar compiled by
   Menhir, or a file of its output ([--sentences FILE]). *)
type generator =
  | Fuzzer of { menhir : string; fuzzer : string; source : string }
  | Saved of string

let sentences_of_output text =
  List.filter
    (fun sentence -> sentence <> "") (String.split_on_char '\000' text)

(* [next], with a blank before it when it would not be lexed as a separate
   token after [previous]. *)
let separated (previous : Ocst.Token.any_token) (next : Ocst.Token.any_token) =
  match next.kind with
  | `EOF -> next
  | _ ->
      let previous =
        Ocst.Token_stream.insert
          Ocst.Token_stream.empty { previous with leading = [] }
      in
      match Ocst.Token_stream.(tokens (insert_create_trivia previous next)) with
      | [ _; next ] -> next
      | _ -> assert false

(* The kind of a failure, without the source: "AST mismatch", "OCST parser
   failed"... *)
let failure_kind ~name message =
  let message =
    if String.starts_with ~prefix:name message then
      String.sub
        message (String.length name)
        (String.length message - String.length name)
    else message
  in
  let message =
    if String.starts_with ~prefix:": " message then
      String.sub message 2 (String.length message - 2)
    else message
  in
  match String.index_opt message ':' with
  | Some index -> String.sub message 0 index
  | None -> message

(* A smaller source failing in the same way as [source]: windows of tokens
   are removed, from the largest to single tokens, as long as [failing]
   holds, within a number of checks, for very long sources. *)
let minimize ?(budget = 5000) ~failing source =
  let budget = ref budget in
  let failing source = !budget > 0 && (decr budget; failing source) in
  let without tokens start length =
    let tokens = Array.of_list tokens in
    let after =
      Array.sub tokens (start + length) (Array.length tokens - start - length)
    in
    if start > 0 then after.(0) <- separated tokens.(start - 1) after.(0);
    Ocst.source_of_tokens
      (Array.to_list (Array.append (Array.sub tokens 0 start) after))
  in
  (* Windows of [length] tokens, from [start]. *)
  let rec windows source length start =
    let tokens = Ocst.lex source in
    if start + length > List.length tokens - 1 then source
    else
      let smaller = without tokens start length in
      if failing smaller then windows smaller length start
      else windows source length (start + 1)
  in
  let rec loop source length =
    let smaller = windows source length 0 in
    if length > 1 then loop smaller (length / 2)
    else if smaller <> source then
      loop smaller (List.length (Ocst.lex smaller) / 2)
    else smaller
  in
  loop source (max 1 (List.length (Ocst.lex source) / 2))

(* The additional mutants of each sentence. *)
type extra =
  | No_extra | Every_token | Mutants of int
  | No_mutants (** No mutant at all, not even the usual ones. *)
  | Doc_comments of { all : bool }
  (** Only the mutants with doc comments: with every separator ([all]), or
      with random separators. *)

(* Invalid variants of a sentence, to check that OCST and the compiler reject
   the same sources, and that OCST then fails with a syntax error: the
   sentence without one of its tokens, a prefix of the sentence, the sentence
   with a random token inserted, and with a token replaced by a random one,
   and the [extra] mutants. The positions and the tokens are chosen from the
   sentence, deterministically. *)
let mutants ?(extra = No_extra) sentence =
  let tokens = Array.of_list (Ocst.lex sentence) in
  (* The tokens before [EOF]. *)
  let count = Array.length tokens - 1 in
  if count < 2 then []
  else
    let random = Random.State.make [| Hashtbl.hash sentence |] in
    let source tokens = Ocst.source_of_tokens (Array.to_list tokens) in
    let deleted = Random.State.int random count in
    let prefix = 1 + Random.State.int random (count - 1) in
    let without =
      Array.append
        (Array.sub tokens 0 deleted)
        (Array.sub tokens (deleted + 1) (Array.length tokens - deleted - 1))
    in
    (* [removed] tokens at [index] replaced by [token], which takes the trivia
       before them. *)
    let splice ?(token = Random_token.random random) index ~removed =
      let token = { token with leading = tokens.(index).leading } in
      let token =
        if index = 0 then token else separated tokens.(index - 1) token
      in
      let after =
        Array.sub
          tokens (index + removed) (Array.length tokens - index - removed)
      in
      after.(0) <- separated token { (after.(0)) with leading = [] };
      source (Array.concat [ Array.sub tokens 0 index; [| token |]; after ])
    in
    let insert ?token () =
      splice ?token (Random.State.int random (count + 1)) ~removed:0
    in
    let replace ?token () =
      splice ?token (Random.State.int random count) ~removed:1
    in
    let inserted = insert () in
    let replaced = replace () in
    let extras =
      match extra with
      | No_extra | No_mutants -> []
      | Every_token ->
          Array.to_list Random_token.all
          |>
          List.concat_map (fun token -> [ insert ~token (); replace ~token () ])
      | Mutants count ->
          List.concat (List.init count (fun _ -> [ insert (); replace () ]))
      | Doc_comments { all } ->
          let separators = [| " "; "\n"; "\n\n" |] in
          (* A doc comment before every token, after [separator ()]. *)
          let documented separator =
            let previous = ref None in
            Array.to_list tokens
            |>
            List.mapi
              ( fun index (token : Ocst.Token.any_token) ->
                  let text = Printf.sprintf "(** d%d *)" index in
                  let doc : Ocst.Token.any_token =
                    { leading = [ Whitespace (separator ()) ];
                      kind = `DOCSTRING text
                    }
                  in
                  let doc =
                    match !previous with
                      Some previous -> separated previous doc
                    | None -> doc
                  in
                  let token = separated doc token in
                  previous := Some token; [ doc; token ]
              )
            |> List.concat |> Array.of_list |> source
          in
          ( if all then
              List.map
                (fun separator -> documented (fun () -> separator))
                (Array.to_list separators)
            else []
          )
          @ [ documented (fun () -> separators.(Random.State.int random 3)) ]
    in
    let usual =
      [ source without; source (Array.sub tokens 0 prefix); inserted; replaced ]
    in
    let mutants =
      match extra with
        Doc_comments _ | No_mutants -> []
      | _ -> usual
    in
    List.sort_uniq compare (List.filter (( <> ) sentence) (mutants @ extras))

(* A configuration of the fuzzer: its entry point and its arguments. The
   exhaustive mode covers all the productions of the grammar, with short
   sentences; random sentences are longer. *)
type configuration =
  { entrypoint : string; arguments : string list; extra : extra }

(* For random sentences: the productions which the semantic actions of
   parser.mly mostly reject, which would make most long sentences invalid
   ([--rejections] shows the others, which are rare): puns [let x] without
   an extension, [_] as an expression, and [nonrec] in type extensions and
   substitutions. The exhaustive mode covers them. *)
let valid =
  [ "--avoid"; "let_binding_body: val_ident"; "--avoid";
    "fun_expr: UNDERSCORE"; "--avoid"; "_: _* NONREC _* PLUSEQ _*";
    "--avoid"; "_: _* NONREC _* COLONEQUAL _*"
  ]

let configurations =
  List.concat_map
    ( fun entrypoint ->
        [ { entrypoint; arguments = [ "--exhaust" ]; extra = No_extra };
          { entrypoint; arguments = [ "--exhaust"; "--comments" ];
            extra = No_extra
          }
        ;
          { entrypoint;
            arguments =
              [ "--seed"; "1"; "--count"; "2000"; "--length"; "60" ] @ valid
          ;
            extra = No_extra
          }
        ;
          { entrypoint;
            arguments =
              [ "--seed"; "2"; "--count"; "500"; "--length"; "200" ] @ valid
          ;
            extra = No_extra
          }
        ;
          { entrypoint;
            arguments =
              [ "--seed"; "3"; "--count"; "1000"; "--length"; "60"; "--comments"
              ]
              @ valid
          ;
            extra = No_extra
          }
        ;
          { entrypoint; arguments = [ "--exhaust" ];
            extra = Doc_comments { all = false }
          }
        ]
    )
    [ "implementation"; "interface" ]

(* The configurations of [runtest], quicker: the exhaustive sentences without
   their mutants, and the random sentences, which are few, with theirs. *)
let quick_configurations =
  List.filter_map
    ( fun configuration ->
        match configuration with
        | { arguments = [ "--exhaust" ]; extra = No_extra; _ } ->
            Some { configuration with extra = No_mutants }
        | { arguments = "--exhaust" :: _; _ } -> None
        | configuration -> Some configuration
    )
    configurations

(* The deep fuzzing, too long for [runtest-full] ([fuzz-deep]): every token
   inserted in every sentence of the exhaustive mode, long random sentences
   with more mutants (avoiding the productions which make most of them
   invalid, as [valid]), a few very long sentences (which also avoid the rare
   causes of rejection: MetaOCaml, string assignments, package types, and
   for a million tokens [(val e : S)] and [let%ext] in classes), and doc
   comments before every token. Each one is compared with [NAME.expected],
   and runs in [parts] rules. *)

type deep = { name : string; parts : int; configuration : configuration }

let huge_valid =
  valid
  @
  [ "--avoid"; "METAOCAML_ESCAPE"; "--avoid"; "METAOCAML_BRACKET_OPEN";
    "--avoid"; "_: _* DOT LBRACKET _* LESSMINUS _*";
    "--avoid"; "_: _* MODULE _* COLON module_type _*";
    "--avoid"; "_: LPAREN MODULE _* module_type RPAREN"
  ]

let million_valid =
  huge_valid
  @
  [ "--avoid"; "expr_colon_package_type: _* COLON _*";
    "--avoid"; "expr_colon_package_type: _* COLONGREATER _*";
    "--avoid"; "let_bindings(no_ext): _* PERCENT _*"
  ]

let deep_configurations =
  let random ~seed ~count ~length valid =
    [ "--seed"; seed; "--count"; count; "--length"; length ] @ valid
  in
  let deep name parts entrypoint arguments extra =
    { name = name ^ "_" ^ entrypoint; parts;
      configuration = { entrypoint; arguments; extra }
    }
  in
  List.concat_map
    ( fun entrypoint ->
        [ deep "fuzz_deep" 16 entrypoint [ "--exhaust" ] Every_token;
          deep
            "fuzz_long" 4 entrypoint
            (random ~seed:"21" ~count:"30000" ~length:"120" valid) (Mutants 10)
        ;
          deep
            "fuzz_docs_exhaust" 4 entrypoint
            [ "--exhaust" ] (Doc_comments { all = true })
        ;
          deep
            "fuzz_docs_comments" 4 entrypoint
            [ "--exhaust"; "--comments" ] (Doc_comments { all = true })
        ;
          deep
            "fuzz_huge_2000" 4 entrypoint
            (random ~seed:"61" ~count:"1000" ~length:"2000" huge_valid)
            (Mutants 5)
        ;
          deep
            "fuzz_huge_20000" 4 entrypoint
            (random ~seed:"62" ~count:"100" ~length:"20000" huge_valid)
            (Mutants 2)
        ;
          deep
            "fuzz_million" 5 entrypoint
            (random ~seed:"71" ~count:"25" ~length:"1000000" million_valid)
            No_extra
        ]
    )
    [ "implementation"; "interface" ]

(* The errors of the compiler on [sentences], by message and text at their
   location, most frequent first, with the shortest example of each. *)
let rejections ~entrypoint sentences =
  let interface = entrypoint = "interface" in
  let groups = Hashtbl.create 64 in
  List.iter
    ( fun sentence ->
        match compiler_error ~interface "fuzz" sentence with
        | None -> ()
        | Some ((loc : Location.t), message) ->
            let start = loc.loc_start.pos_cnum
            and stop = loc.loc_end.pos_cnum
            in
            let text =
              if
                start >= 0 && stop <= String.length sentence && start <= stop
              then String.sub sentence start (min 30 (stop - start))
              else ""
            in
            let message = List.hd (String.split_on_char '\n' message) in
            let key = message, text in
            (* The sentence, or the text before the error for long ones. *)
            let sentence =
              if
                String.length sentence <= 300 || start < 0
                || start > String.length sentence
              then sentence
              else
                "..." ^ String.sub sentence (max 0 (start - 60)) (min 60 start)
                ^ "<HERE>"
            in
            let count, example =
              Option.value (Hashtbl.find_opt groups key) ~default:(0, sentence)
            in
            let example =
              if String.length sentence < String.length example then sentence
              else example
            in
            Hashtbl.replace groups key (count + 1, example)
    )
    sentences
  ;
  let groups = List.of_seq (Hashtbl.to_seq groups) in
  let total =
    List.fold_left (fun total (_, (count, _)) -> total + count) 0 groups
  in
  Printf.printf
    "%s: %d sentences, %d rejected by the compiler\n"
    entrypoint (List.length sentences) total
  ;
  List.sort (fun (_, (left, _)) (_, (right, _)) -> compare right left) groups
  |>
  List.iteri
    ( fun index ((message, text), (count, example)) ->
        if index < 40 then
          Printf.printf "%6d  %s [%s]\n        %S\n" count message text example
    )

(* {1 Dune rules}

   The configurations run in parallel, each in its dune rule, the exhaustive
   ones in [parts] (sentence [k] in part [k mod parts]); the outputs of the
   rules of a group are concatenated, and compared with its [.expected]
   file. [--dune-rules test] prints the rules of test/fuzz.inc,
   [--dune-rules coverage] those of test/coverage/fuzz.inc.

   The fuzzer runs once for each entry point and arguments, in a rule of
   test/fuzz.inc which saves its sentences ([--generate]) in [_build], for
   the rules of the parts of all the configurations with them, in test and
   in test/coverage ([--sentences FILE]). *)

(** The files of the sentences, in test: for each entry point and arguments,
    the file and the selection of the first configuration with them. *)
let sentence_files =
  List.fold_left
    ( fun files (configuration, file, selection) ->
        let key = configuration.entrypoint, configuration.arguments in
        if List.mem_assoc key files then files
        else files @ [ key, (file, selection) ]
    )
    []
    ( List.mapi
        ( fun index configuration ->
            ( configuration, Printf.sprintf "fuzz_%d.sentences" index,
              Printf.sprintf "--configuration %d" index
            )
        )
        configurations
      @
      List.map
        ( fun { name; configuration; _ } ->
            configuration, name ^ ".sentences", "--deep " ^ name
        )
        deep_configurations
    )

(** The option which reads the sentences of [configuration] from their file,
    in a rule of [directory] (test or test/coverage). *)
let sentences_option ~directory { entrypoint; arguments; _ } =
  let file, _ = List.assoc (entrypoint, arguments) sentence_files in
  Printf.sprintf
    "--sentences %%{dep:%s%s}"
    (if directory = "coverage" then "../" else "") file

let parts { arguments; _ } = if List.mem "--exhaust" arguments then 4 else 1

(** The parts of a configuration (its [index] in the list which [selection]
    selects): the arguments and the name of each rule. *)
let configuration_parts
    ~directory ~name ~selection ~mutants_only index configuration
  =
    let count = parts configuration in
    List.init
      count
      ( fun part ->
          ( Printf.sprintf
              "%s %s--configuration %d --part %d/%d%s"
              (sentences_option ~directory configuration) selection index
              part count (if mutants_only then " --mutants-only" else "")
            ,
            Printf.sprintf "%s_%d_%d" name index part
          )
      )

(** The rules of [parts], each writing its output in [NAME.part]. *)
let part_rules buffer parts =
  List.iter
    (fun (arguments, part) -> Printf.bprintf buffer "\n(rule\n (package fromage)\n (targets %s.part)\n (action\n  (with-stdout-to\n   %%{targets}\n   (run ./fuzz_roundtrip.exe %s))))\n" part arguments) parts

(** The rule of a group, which compares the outputs of its [parts] with
    [NAME.expected]. *)
let group_rule buffer ~alias ~name parts =
  Printf.bprintf
    buffer "\n(rule\n (alias %s)\n (package fromage)\n (targets %s.actual)\n (deps%s)\n (action\n  (progn\n   (with-stdout-to %%{targets} (cat %%{deps}))\n   (diff %s.expected %%{targets}))))\n" alias name
    (String.concat "" (List.map (fun part -> " " ^ part ^ ".part") parts)) name

let quick entrypoint =
  List.filter
    (fun configuration -> configuration.entrypoint = entrypoint)
    quick_configurations

let rec index_of predicate index =
  function
  | value :: rest ->
      if predicate value then Some index
      else index_of predicate (index + 1) rest
  | [] -> None

let dune_rules directory =
  let buffer = Buffer.create 4096 in
  let add format = Printf.bprintf buffer format in
  add
    "; Generated by [fuzz_roundtrip.exe --dune-rules %s] (see fuzz_roundtrip.ml):\n\
     ; [dune build @runtest] checks it, [dune promote] updates it.\n"
    directory
  ;
  begin match directory with
  | "test" ->
      List.iter
        (fun (_, (file, selection)) -> add "\n(rule\n (targets %s)\n (action\n  (with-stdout-to\n   %%{targets}\n   (run ./fuzz_roundtrip.exe %%{bin:menhir} %%{bin:ocamlgrammarfuzzer} %%{dep:parser.mly} %s --generate))))\n" file selection) sentence_files
      ;
      (* The quick groups, for [runtest]. *)
      let quick_name entrypoint = "fuzz_quick_" ^ entrypoint in
      let quick_parts entrypoint index configuration =
        configuration_parts
          ~directory ~name:(quick_name entrypoint)
          ~selection:(Printf.sprintf "--quick %s " entrypoint)
          ~mutants_only:false index configuration
      in
      List.iter
        ( fun entrypoint ->
            let parts =
              List.concat
                (List.mapi (quick_parts entrypoint) (quick entrypoint))
            in
            part_rules buffer parts;
            group_rule
              buffer ~alias:"runtest"
              ~name:(quick_name entrypoint) (List.map snd parts)
        )
        [ "implementation"; "interface" ]
      ;
      (* The full group, for [runtest-full], which also runs the quick
         groups: it reuses their outputs for the same configurations, and
         checks only the mutants of the configurations whose sentences they
         check. *)
      let included = ref [] in
      let outputs =
        List.concat
          ( List.mapi
              ( fun index configuration ->
                  let entrypoint = configuration.entrypoint in
                  let quick = quick entrypoint in
                  match index_of (( = ) configuration) 0 quick with
                  | Some quick_index ->
                      List.map
                        snd (quick_parts entrypoint quick_index configuration)
                  | None ->
                      let same_sentences =
                        index_of
                          ( fun quick ->
                              quick.arguments = configuration.arguments
                          )
                          0 quick
                      in
                      let sentences =
                        match same_sentences with
                        | Some quick_index when
                            not (List.mem (entrypoint, quick_index) !included)
                        ->
                            included := (entrypoint, quick_index) :: !included;
                            List.map
                              snd
                              ( quick_parts
                                  entrypoint quick_index
                                  (List.nth quick quick_index)
                              )
                        | _ -> []
                      in
                      let parts =
                        configuration_parts
                          ~directory ~name:"fuzz_roundtrip" ~selection:""
                          ~mutants_only:(same_sentences <> None)
                          index configuration
                      in
                      part_rules buffer parts; sentences @ List.map snd parts
              )
              configurations
          )
      in
      group_rule buffer ~alias:"runtest-full" ~name:"fuzz_roundtrip" outputs;
      (* The deep fuzzing, each configuration in its parts. *)
      List.iter
        ( fun { name; parts; configuration } ->
            let parts =
              List.init
                parts
                ( fun part ->
                    ( Printf.sprintf
                        "%s --deep %s --part %d/%d"
                        (sentences_option ~directory configuration)
                        name part parts
                      ,
                      Printf.sprintf "%s_%d" name part
                    )
                )
            in
            part_rules buffer parts;
            group_rule buffer ~alias:"fuzz-deep" ~name (List.map snd parts)
        )
        deep_configurations
  | "coverage" ->
      (* All the configurations, instrumented, those whose sentences an
         earlier one checks with only their mutants. *)
      let seen = ref [] in
      List.iteri
        ( fun index configuration ->
            let sentences = configuration.entrypoint, configuration.arguments in
            let mutants_only = List.mem sentences !seen in
            seen := sentences :: !seen;
            List.iter
              (fun (arguments, part) -> add "\n(rule\n (package ocst)\n (enabled_if %%{lib-available:bisect_ppx})\n (targets %s.coverage)\n (action\n  (progn\n   (setenv BISECT_FILE %s_\n    (ignore-stdout\n     (run ./fuzz_roundtrip.exe %s)))\n   (system \"%%{bin:bisect-ppx-report} merge %s.coverage %s_*.coverage\"))))\n" part part arguments part part)
              ( configuration_parts
                  ~directory ~name:"fuzz" ~selection:""
                  ~mutants_only index configuration
              )
        )
        configurations
  | _ -> failwith "usage: fuzz_roundtrip.exe --dune-rules (test | coverage)"
  end;
  Buffer.contents buffer

(** [name VALUE], anywhere in [arguments]: [Some VALUE], and the other
    arguments. *)
let rec take_option name =
  function
  | option :: value :: rest when option = name ->
      Some value, snd (take_option name rest)
  | argument :: rest ->
      let value, rest = take_option name rest in
      value, argument :: rest
  | [] -> None, []

let () =
  Warnings.parse_options false "-a" |> ignore;
  (* [--timings], anywhere: the time of each configuration and of each phase,
     on the error output. *)
  let timings = Array.mem "--timings" Sys.argv
  (* [--mutants-only], anywhere: only the mutants of the sentences are
     checked, when another rule checks the sentences (see
     {!section-dune_rules}). *)
  and mutants_only = Array.mem "--mutants-only" Sys.argv
  (* [--generate], anywhere: the sentences of the configuration are printed
     (as the fuzzer prints them), for [--sentences FILE], instead of being
     checked. *)
  and generate = Array.mem "--generate" Sys.argv
  in
  let arguments =
    List.filter
      ( fun argument ->
          not
            (List.mem argument [ "--timings"; "--mutants-only"; "--generate" ])
      )
      (Array.to_list Sys.argv)
  in
  (* [--configuration I] and [--part I/N], anywhere: only the [I]th
     configuration (from 0) of those selected, and only its sentences of
     index [I] modulo [N] (see {!section-dune_rules}). *)
  let only, arguments = take_option "--configuration" arguments in
  let only = Option.map int_of_string only in
  let part, arguments = take_option "--part" arguments in
  (* [--deep NAME], anywhere: the configuration of the deep fuzzing [NAME]
     (see [deep_configurations]). *)
  let deep, arguments = take_option "--deep" arguments in
  let saved, arguments = take_option "--sentences" arguments in
  let part =
    Option.map
      (fun text -> Scanf.sscanf text "%d/%d" (fun part count -> part, count))
      part
  in
  begin match take_option "--dune-rules" arguments with
  | Some directory, _ -> print_string (dune_rules directory); exit 0
  | None, _ -> ()
  end;
  begin match arguments with
  | _ :: menhir :: fuzzer :: source :: "--rejections" :: entrypoint :: arguments
  ->
      let cmly = grammar ~menhir source in
      rejections
        ~entrypoint
        ( sentences_of_output
            ( fuzzer_output
                ~fuzzer ~cmly ([ "--entrypoint"; entrypoint ] @ arguments)
            )
        )
      ;
      exit 0
  | _ :: _ :: _ :: _ :: "--rejections" :: _ -> failwith "usage: fuzz_roundtrip.exe MENHIR FUZZER GRAMMAR --rejections ENTRYPOINT ARGUMENTS..."
  | _ -> ()
  end;
  let rec options extra =
    function
    | "--every-token" :: rest -> options Every_token rest
    | "--mutants" :: count :: rest ->
        options (Mutants (int_of_string count)) rest
    | "--doc-comments" :: rest -> options (Doc_comments { all = true }) rest
    | rest -> extra, rest
  in
  let generator, rest =
    match saved, arguments with
    | Some file, _ :: rest -> Saved file, rest
    | None, _ :: menhir :: fuzzer :: source :: rest ->
        Fuzzer { menhir; fuzzer; source }, rest
    | _ ->
        failwith
          "usage: fuzz_roundtrip.exe (MENHIR FUZZER GRAMMAR | --sentences FILE) [--quick [ENTRYPOINT] | --every-token | --mutants N | \
           --doc-comments] [ENTRYPOINT FUZZER-ARGUMENTS...]"
  in
  let configurations =
    match options No_extra rest with
    | No_extra, [] -> configurations
    | No_extra, "--quick" :: entrypoints ->
        List.filter
          ( fun { entrypoint; _ } ->
              entrypoints = [] || List.mem entrypoint entrypoints
          )
          quick_configurations
    | extra, [] ->
        List.map
          (fun configuration -> { configuration with extra }) configurations
    | extra, entrypoint :: arguments -> [ { entrypoint; arguments; extra } ]
  in
  let configurations =
    match only, deep with
    | _, Some name ->
        [ ( List.find (fun deep -> deep.name = name) deep_configurations
          ).configuration
        ]
    | None, None -> configurations
    | Some index, None -> [ List.nth configurations index ]
  in
  (* The output of the fuzzer for a configuration. *)
  let fuzz =
    match generator, configurations with
    | Fuzzer { menhir; fuzzer; source }, _ ->
        let cmly = grammar ~menhir source in
        fun { entrypoint; arguments; _ } ->
          fuzzer_output
            ~fuzzer ~cmly ([ "--entrypoint"; entrypoint ] @ arguments)
    | Saved file, [ _ ] ->
        fun _ -> In_channel.with_open_bin file In_channel.input_all
    | Saved _, _ ->
        failwith "--sentences FILE: the sentences of a single configuration"
  in
  begin if generate then
      match configurations with
      | [ configuration ] -> print_string (fuzz configuration); exit 0
      | _ -> failwith "--generate: the sentences of a single configuration"
  end;
  let failures =
    List.concat_map
      ( fun ({ entrypoint; arguments; extra } as configuration) ->
          let start = Unix.gettimeofday () in
          let sentences =
            Roundtrip.timed
              "generate the sentences"
              (fun () -> sentences_of_output (fuzz configuration))
          in
          let sentences =
            match part with
            | None -> sentences
            | Some (part, count) ->
                List.filteri (fun index _ -> index mod count = part) sentences
          in
          let options =
            match extra with
            | No_extra -> ""
            | No_mutants -> " (no mutants)"
            | Every_token -> " --every-token"
            | Mutants count -> Printf.sprintf " --mutants %d" count
            | Doc_comments { all = true } -> " --doc-comments"
            | Doc_comments { all = false } -> " (doc comments)"
          in
          let options =
            match part with
            | Some (part, count) when count > 1 ->
                Printf.sprintf "%s --part %d/%d" options part count
            | _ -> options
          in
          (* The mutants which both parsers accept, which are compared. *)
          let checked = ref 0
          and accepted = ref 0
          and valid = ref 0
          in
          let check =
            if entrypoint = "interface" then check_interface
            else check_implementation
          in
          let filename =
            if entrypoint = "interface" then "fuzz.mli" else "fuzz.ml"
          in
          (* The failures are also shown as they happen, for long runs. *)
          let check_sentence ~kind sentence =
            let name = Printf.sprintf "%s%s %S" entrypoint kind sentence in
            let failure =
              failure
                ~name
                ( fun () ->
                    let both = check ~name filename sentence in
                    if
                      kind <> ""
                    then begin incr checked; if both then incr accepted end
                    else if both then incr valid
                )
            in
            Option.iter
              ( fun { message; details } ->
                  let kind = failure_kind ~name message in
                  (* The backtrace of an exception of OCST. *)
                  if
                    kind = "OCST raised an exception"
                    || kind = "OCST internal error"
                  then
                    Option.iter
                      (fun details -> prerr_string (Lazy.force details)) details
                  ;
                  let failing source =
                    match
                      Roundtrip.failure
                        ~name (fun () -> ignore (check ~name filename source))
                    with
                    | Some { message; _ } -> failure_kind ~name message = kind
                    | None -> false
                  in
                  Printf.eprintf
                    "%s\n  minimized: %S\n%!" message
                    (minimize ~failing sentence)
              )
              failure
            ;
            failure
          in
          let failures =
            List.concat_map
              ( fun sentence ->
                  ( if mutants_only then []
                    else Option.to_list (check_sentence ~kind:"" sentence)
                  )
                  @
                  List.filter_map
                    (check_sentence ~kind:" mutant")
                    ( Roundtrip.timed
                        "make the mutants" (fun () -> mutants ~extra sentence)
                    )
              )
              sentences
          in
          if mutants_only then
            Printf.printf
              "%s %s%s (mutants only): %d mutants (%d accepted)\n%!" entrypoint
              (String.concat " " arguments) options !checked !accepted
          else
            Printf.printf
              "%s %s%s: %d sentences (%d accepted by both parsers), %d mutants (%d accepted)\n%!" entrypoint (String.concat " " arguments) options
              (List.length sentences) !valid !checked !accepted
          ;
          if timings then
            Printf.eprintf
              "%8.2fs  %s %s%s\n%!" (Unix.gettimeofday () -. start)
              entrypoint (String.concat " " arguments) options
          ;
          failures
      )
      configurations
  in
  if timings then Roundtrip.print_timings ();
  report ~title:"OCST fuzzing round-trip" failures
